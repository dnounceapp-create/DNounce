-- Safe to run: it only creates a new table. Running it twice changes nothing.

CREATE TABLE IF NOT EXISTS public.prospect_profiles (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  first_name         text NOT NULL,
  last_name          text NOT NULL,
  company_name       text,
  nickname           text,
  phone              text NOT NULL UNIQUE CHECK (phone ~ '^[0-9]{10}$'),
  email              text,
  neighborhood       text NOT NULL,
  -- system fields
  claim_code         text NOT NULL UNIQUE DEFAULT replace(gen_random_uuid()::text, '-', ''),
  status             text NOT NULL DEFAULT 'not_contacted'
                     CHECK (status IN ('not_contacted','contacted','invited','claimed','declined','do_not_contact')),
  existing_subject_id uuid,   -- already on DNounce with this phone: never create a second profile
  claimed_subject_id uuid,
  notes              text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now()
);

-- Locked: no public or signed-in access at all. Only the server (admin) can read it.
ALTER TABLE public.prospect_profiles ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.prospect_profiles FROM anon, authenticated;

